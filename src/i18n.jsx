export const normalizeLanguage = value => value === "pt-BR" ? "pt-BR" : "en";
const LOWER_PORTUGUESE = Object.fromEntries(Object.entries(PORTUGUESE).map(([key,value]) => [key.toLowerCase(),value]));
export const translate = (text, language) => {
  if (language !== "pt-BR" || typeof text !== "string") return text;
  if (Object.hasOwn(PORTUGUESE,text)) return PORTUGUESE[text];
  const known = Object.hasOwn(LOWER_PORTUGUESE,text.toLowerCase()) ? LOWER_PORTUGUESE[text.toLowerCase()] : undefined;
  return known ? (text === text.toUpperCase() ? known.toUpperCase() : known) : text;
};
export const currentLanguage = () => { try { return normalizeLanguage(document.documentElement.lang); } catch { return "en"; } };
export const translateCurrent = text => translate(text,currentLanguage());
const LanguageContext = createContext({ language: "en", setLanguage: () => {}, translateUI: text => text });
export function LanguageProvider({ children }) {
  const [language, updateLanguage] = useState(() => {
    try { return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY)); } catch { return "en"; }
  });
  const setLanguage = value => updateLanguage(normalizeLanguage(value));
  useEffect(() => {
    document.documentElement.lang = language;
    try { localStorage.setItem(LANGUAGE_STORAGE_KEY, language); } catch { /* Private browsers may block storage; language still works for this visit. */ }
  }, [language]);
  return <LanguageContext.Provider value={{ language, setLanguage, translateUI: text => translate(text, language), interpolateUI: (key, values) => interpolate(key, values, language) }}>{children}</LanguageContext.Provider>;
}
export const useLanguage = () => useContext(LanguageContext);
export function LanguageSelector({ dark }) {
  const { language, setLanguage, translateUI } = useLanguage();
  return <label className="flex items-center gap-2 text-xs font-semibold py-2" style={{color:dark ? "#FFFFFF" : "#0A0710"}}>
    <span>{translateUI("Language")}</span>
    <select aria-label={translateUI("Language")} value={language} onChange={event => setLanguage(event.target.value)} className="rounded-lg px-2 py-2 border" style={{background:dark ? "#180C28" : "#FFFFFF",color:dark ? "#FFFFFF" : "#0A0710"}}>
      <option value="en">English</option><option value="pt-BR">Português</option>
    </select>
  </label>;
}

export const interpolate = (key, values, language) => {
  const slots = {"Mark as {0}":[0],"Quantity ({0})":[0],"New counted quantity ({0}) — system says {1}":[0],"No {0} yet":[0],"New {0}":[0]};
  return translate(key, language).replace(/\{(\d+)\}/g, (_, index) => String((slots[key] || []).includes(Number(index)) ? translate(values[Number(index)] ?? "", language) : (values[Number(index)] ?? "")));
};

export const interpolateCurrent = (key, values) => interpolate(key, values, currentLanguage());
