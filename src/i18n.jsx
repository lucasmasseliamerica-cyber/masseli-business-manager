export const normalizeLanguage = value => value === "pt-BR" ? "pt-BR" : "en";
export const translate = (text, language) => language === "pt-BR" && typeof text === "string" ? (PORTUGUESE[text] ?? text) : text;
const LanguageContext = createContext({ language: "en", setLanguage: () => {}, translateUI: text => text });
export function LanguageProvider({ children }) {
  const [language, updateLanguage] = useState(() => {
    try { return normalizeLanguage(localStorage.getItem(LANGUAGE_STORAGE_KEY)); } catch { return "en"; }
  });
  const setLanguage = value => updateLanguage(normalizeLanguage(value));
  useEffect(() => {
    document.documentElement.lang = language;
    try { localStorage.setItem(LANGUAGE_STORAGE_KEY, language); } catch { /* Private browsers may block storage; language still works for this visit. */ }
  }, [language]);
  return <LanguageContext.Provider value={{ language, setLanguage, translateUI: text => translate(text, language) }}>{children}</LanguageContext.Provider>;
}
export const useLanguage = () => useContext(LanguageContext);
export function LanguageSelector({ dark }) {
  const { language, setLanguage, translateUI } = useLanguage();
  return <label className="flex items-center gap-2 text-xs font-semibold py-2" style={{color:dark ? "#FFFFFF" : "#0A0710"}}>
    <span>{translateUI("Language")}</span>
    <select aria-label={translateUI("Language")} value={language} onChange={event => setLanguage(event.target.value)} className="rounded-lg px-2 py-2 border" style={{background:dark ? "#180C28" : "#FFFFFF",color:dark ? "#FFFFFF" : "#0A0710"}}>
      <option value="en">English</option><option value="pt-BR">Português</option>
    </select>
  </label>;
}
